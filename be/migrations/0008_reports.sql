-- 0008_reports.sql — automatic daily report archive (GUIDE #10 C, flow §23 step 10). Additive only.
CREATE TABLE report_runs (
  id               BIGSERIAL PRIMARY KEY,
  report_type      TEXT NOT NULL
                   CHECK (report_type IN ('daily-coverage', 'vehicle-wise', 'agency-wise', 'ward-wise', 'missed-pids')),
  operational_date DATE NOT NULL,
  format           TEXT NOT NULL CHECK (format IN ('xlsx', 'csv', 'pdf')),
  file_path        TEXT,                    -- relative to REPORTS_DIR (never absolute)
  size_bytes       BIGINT,
  row_count        INTEGER,
  status           TEXT NOT NULL CHECK (status IN ('RUNNING', 'SUCCESS', 'FAILED')),
  finalized        BOOLEAN NOT NULL DEFAULT true, -- false = generated before every assignment of the day was finalized
  error            TEXT,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  finished_at      TIMESTAMPTZ
);
-- Idempotency: at most one successful file per (type, day, format).
CREATE UNIQUE INDEX uq_report_runs_success ON report_runs (report_type, operational_date, format) WHERE status = 'SUCCESS';
CREATE INDEX idx_report_runs_date ON report_runs (operational_date DESC, report_type);
COMMENT ON TABLE report_runs IS 'Daily report files generated by the archive job (GUIDE #10 C). Files live under REPORTS_DIR.';
